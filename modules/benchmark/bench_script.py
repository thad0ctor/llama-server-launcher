"""Export a benchmark run as a portable ``.sh`` / ``.ps1`` script.

A run is a list of commands (one for llama-bench, N for a llama-sweep-bench
matrix). The generated scripts reproduce exactly what :class:`BenchRunner`
would execute, so a user can commit them, run them on another machine, or
tweak flags by hand.

The bash generator mirrors ``plan_to_shell_script`` in
``modules/build/build_runner.py`` (env-shebang, ``set -e``, closed stdin).
The PowerShell generator mirrors the single-quoted-literal quoting used by
``LaunchManager._build_ps_cmd_parts`` so ``$``/``$(...)``/backticks in a
model path can't be interpreted before the native exe sees them.
"""

from __future__ import annotations

import re
import shlex

Command = list[str]

# A valid POSIX/PowerShell environment-variable name. An env KEY is emitted
# verbatim into the prelude (``export KEY=...`` / ``$env:KEY = ...``), so a key
# containing whitespace, newlines, ``;`` or ``$(...)`` would become executable
# script syntax rather than an assignment. Keys that don't match are dropped
# from the prelude (values are always quoted); the saved script is still
# produced. The source that builds ``env`` also filters, so this is defence in
# depth.
_ENV_KEY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def _sh_quote(token: str) -> str:
    return shlex.quote(str(token))


def _ps_quote(token: str) -> str:
    """Single-quoted PowerShell literal (embedded ``'`` doubled)."""
    return "'" + str(token).replace("'", "''") + "'"


def _sh_env_quote(value: str) -> str:
    """Single-quoted bash literal for an env value (embedded ``'`` escaped).

    Always wraps in single quotes (unlike ``shlex.quote``, which omits them for
    already-safe values) so the prelude reads uniformly as ``KEY='value'``.
    """
    return "'" + str(value).replace("'", "'\\''") + "'"


def to_sh(
    commands: list[Command],
    *,
    header: str = "",
    env: dict[str, str] | None = None,
    env_unset: list[str] | None = None,
) -> str:
    """Render ``commands`` as a self-contained bash script.

    When ``env`` is given, an ``export KEY='value'`` prelude (sorted keys) is
    emitted before the commands so a saved script sees the same environment the
    in-app run set up (e.g. ``CUDA_VISIBLE_DEVICES``). ``env_unset`` names
    variables to actively ``unset`` (e.g. removing an inherited stale
    ``CUDA_VISIBLE_DEVICES`` when the resolver asked for ``unset``).
    """
    lines: list[str] = ["#!/usr/bin/env bash"]
    if header:
        for hl in header.splitlines():
            lines.append(f"# {hl}")
    else:
        lines.append("# Benchmark script generated by llama-server-launcher")
    # Intentionally NO `set -e`: a failed combo (e.g. an OOM at one
    # ctx/gpu-layer setting) must not abort the rest of the matrix. This
    # mirrors the in-app BenchRunner, which continues and reports a failed
    # count rather than fail-fast. Close stdin so no tool blocks on input.
    lines.append("exec </dev/null")
    lines.append("")
    if env or env_unset:
        for key in sorted(env or {}):
            if not _ENV_KEY_RE.match(key):
                # A key with shell-active characters would inject script syntax
                # into the prelude; drop it rather than emit executable garbage.
                continue
            lines.append(f"export {key}={_sh_env_quote(env[key])}")
        for key in sorted(env_unset or []):
            if _ENV_KEY_RE.match(key):
                lines.append(f"unset {key}")
        lines.append("")
    total = len(commands)
    multi = total > 1
    if multi:
        # Track whether any combo failed so the script's own exit status
        # reflects it, while still continuing past individual failures.
        lines.append("_bench_rc=0")
        lines.append("")
    for i, cmd in enumerate(commands, start=1):
        if not cmd:
            continue
        rendered = " ".join(_sh_quote(tok) for tok in cmd)
        if multi:
            lines.append(f'echo "== benchmark {i}/{total} =="')
            # Continue past a nonzero exit, but remember the failure and surface
            # it on stderr. Capture $? first: assigning _bench_rc would reset it.
            lines.append(
                f"{rendered} || {{ _rc=$?; _bench_rc=1; "
                f'echo "== benchmark {i}/{total} FAILED (exit $_rc) ==" >&2; }}'
            )
        else:
            # A single command's own exit status is the script's exit status.
            lines.append(rendered)
        lines.append("")
    if multi:
        lines.append('exit "$_bench_rc"')
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def to_ps1(
    commands: list[Command],
    *,
    header: str = "",
    env: dict[str, str] | None = None,
    env_unset: list[str] | None = None,
) -> str:
    """Render ``commands`` as a self-contained PowerShell script.

    When ``env`` is given, a ``$env:KEY = 'value'`` prelude (sorted keys) is
    emitted before the commands so a saved script sees the same environment the
    in-app run set up (e.g. ``CUDA_VISIBLE_DEVICES``). ``env_unset`` names
    variables to remove (``Remove-Item Env:KEY``) so an inherited stale value
    can't leak into the run.
    """
    lines: list[str] = []
    if header:
        for hl in header.splitlines():
            lines.append(f"# {hl}")
    else:
        lines.append("# Benchmark script generated by llama-server-launcher")
    # 'Continue' (not 'Stop') so one failed combo doesn't abort the rest of
    # the matrix — mirrors the in-app BenchRunner. (Native exe failures don't
    # throw in PowerShell anyway; this also covers any cmdlet errors.)
    lines.append("$ErrorActionPreference = 'Continue'")
    lines.append("")
    if env or env_unset:
        for key in sorted(env or {}):
            if not _ENV_KEY_RE.match(key):
                # A key with shell-active characters would inject script syntax
                # into the prelude; drop it rather than emit executable garbage.
                continue
            lines.append(f"$env:{key} = {_ps_quote(env[key])}")
        for key in sorted(env_unset or []):
            if _ENV_KEY_RE.match(key):
                lines.append(f"Remove-Item -Path Env:{key} -ErrorAction SilentlyContinue")
        lines.append("")
    total = len(commands)
    multi = total > 1
    if multi:
        # Track whether any combo failed so the script's own exit status
        # reflects it, while still continuing past individual failures.
        lines.append("$_benchRc = 0")
        lines.append("")
    for i, cmd in enumerate(commands, start=1):
        if not cmd:
            continue
        if multi:
            lines.append(f'Write-Host "== benchmark {i}/{total} =="')
        # First token is the executable, invoked with the call operator.
        parts = ["& " + _ps_quote(cmd[0])]
        parts += [_ps_quote(tok) for tok in cmd[1:]]
        lines.append(" ".join(parts))
        # Capture $? (the last command's success) BEFORE anything else can reset
        # it: a native exe that fails to launch leaves $LASTEXITCODE stale, so
        # $? is the reliable signal.
        lines.append("$_benchSucceeded = $?")
        if multi:
            # Split launch failure from a nonzero exit code: on a launch failure
            # $LASTEXITCODE is stale (could be 0 from a prior command), so don't
            # print it — report the launch error distinctly.
            lines.append(
                f"if (-not $_benchSucceeded) {{ $_benchRc = 1; "
                f'Write-Host "== benchmark {i}/{total} FAILED (launch error) ==" }}'
            )
            lines.append(
                f"elseif ($LASTEXITCODE -ne 0) {{ $_benchRc = 1; "
                f'Write-Host "== benchmark {i}/{total} FAILED (exit $LASTEXITCODE) ==" }}'
            )
        else:
            # A single command's status is the script's status. If it failed to
            # even run ($? is false) exit nonzero; otherwise propagate its code.
            lines.append("if (-not $_benchSucceeded) { exit 1 }")
            lines.append("exit $LASTEXITCODE")
        lines.append("")
    if multi:
        lines.append("exit $_benchRc")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def render(
    commands: list[Command],
    fmt: str,
    *,
    header: str = "",
    env: dict[str, str] | None = None,
    env_unset: list[str] | None = None,
) -> str:
    if fmt == "sh":
        return to_sh(commands, header=header, env=env, env_unset=env_unset)
    if fmt == "ps1":
        return to_ps1(commands, header=header, env=env, env_unset=env_unset)
    raise ValueError(f"unknown script format {fmt!r}")
